def preset_digest(library, preset_id):
    digest = hashlib.sha256()
    for seed in SEEDS:
        for complexity in COMPLEXITIES:
            for density in DENSITIES:
                for mode in MODES:
                    prompt = library.generate(
                        preset_id, seed, complexity=complexity, density=density, mode=mode,
                        lyrics=LYRICS if mode == "vocal" else None,
                    )
                    head = f"{seed}|{complexity}|{density}|{mode}|{prompt.bpm}|{prompt.meter}|{prompt.title}\n"
                    digest.update(head.encode("utf-8"))
                    digest.update(prompt.style.encode("utf-8"))
                    digest.update(b"\n--\n")
    return digest.hexdigest()


class GoldenFreezeTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.library = load_library()

    def test_the_freeze_itself_is_well_formed(self):
        ids = [row[0] for row in FROZEN]
        self.assertEqual(len(ids), 384)
        self.assertEqual(len(set(ids)), 384)
        self.assertEqual(ids, [f"{p}/{a}" for p in PALETTE_IDS for a in ARRANGEMENT_IDS])
        self.assertEqual((len(PALETTE_IDS), len(ARRANGEMENT_IDS)), (32, 12))
        self.assertTrue(all(len(row[1]) == 64 for row in FROZEN))

    def test_every_original_preset_id_still_exists_in_the_original_order(self):
        current = [preset.id for preset in self.library.presets]
        position = {preset_id: index for index, preset_id in enumerate(current)}
        frozen_ids = [row[0] for row in FROZEN]
        missing = [preset_id for preset_id in frozen_ids if preset_id not in position]
        self.assertEqual(missing, [], "an original preset id disappeared from the catalog")
        order = [position[preset_id] for preset_id in frozen_ids]
        self.assertEqual(order, sorted(order), "original presets must keep their relative order")
        self.assertEqual([p.id for p in self.library.palettes[:32]], list(PALETTE_IDS))
        self.assertEqual([a.id for a in self.library.arrangements[:12]], list(ARRANGEMENT_IDS))

    def test_composed_text_of_every_original_preset_is_unchanged(self):
        changed = [
            preset_id for preset_id, expected in FROZEN
            if preset_digest(self.library, preset_id) != expected
        ]
        self.assertEqual(
            changed, [],
            f"{len(changed)} original preset(s) now compose different text. This must never happen: "
            "fix the data or compiler change instead of updating this freeze.",
        )


